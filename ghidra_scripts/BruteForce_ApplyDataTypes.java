    private void cls(String name, int size, boolean sizeKnown) {
        cur = new StructureDataType(CAT, name, size, dtm);
        cur.setDescription("Game data class <" + name + "> (Milestones 68-71). "
            + (sizeKnown ? "Size from " + name + "_Create." : "Size not known (last field + 4)."));
        all.put(name, cur);
    }

    private void fld(int off, String name, String kind, long hash, int width, String comment) {
        DataType t = width == 1 ? ByteDataType.dataType
            : width == 2 ? Undefined2DataType.dataType
            : kind.equals("hash") ? UnsignedIntegerDataType.dataType
            : kind.equals("float") ? FloatDataType.dataType
            : kind.equals("int") ? IntegerDataType.dataType
            : Undefined4DataType.dataType;
        String pre = kind.equals("hash") ? "name hash; "
            : kind.equals("float") || kind.equals("int") ? "type from its values in the data files; "
            : kind.equals("text") ? "text in the data files (enum, name hash or pointer here); " : "";
        String c = pre + comment + String.format(" (field hash 0x%08X)", hash);
        cur.replaceAtOffset(off, t, t.getLength(), name, c);
        nFields++;
    }

