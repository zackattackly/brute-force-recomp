// fixed offset; the hashes are matched to the names in tools/names.json (Milestones 68-71).
// Trigger classes come from their own serializers (Trigger*_ReadProperty).
// Also sets the return type of each <Class>_Create to a pointer to its structure.
// Run after BruteForce_ApplyNames.java. Safe to run more than once.
//@category BruteForce
